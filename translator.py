# translator.py
import re
import sys
from gigachat import GigaChat
from gigachat.models import Chat, Messages, MessagesRole

from lexicons import (
    CORP_RULES, ESO_RULES,
    CORP_PREFIX, CORP_SUFFIX,
    ESO_PREFIX, ESO_SUFFIX,
)

MAX_INPUT_CHARS = 250  # ~3 предложения средней длины на русском

# ============================================================
# ПРОМПТЫ С FEW-SHOT ПРИМЕРАМИ И ГРАНИЦАМИ
# ============================================================

SYSTEM_PROMPT_CORP = """
Ты — переводчик на корпоративно-ебланский язык. Это псевдоделовой жаргон:
англицизмы, пустые глаголы, псевдоглубокомысленные конструкции, за которыми
нет конкретики. Носители — мидл-менеджмент, HR, амбассадоры брендов.

ПРИМЕРЫ ПЕРЕВОДА:
1. Вход: "Надо обсудить бюджет на следующий квартал"
   Выход: "Коллеги, предлагаю синкнуться по фреймворку бюджетирования
   на следующий квартал и зафиксировать ожидания стейкхолдеров."

2. Вход: "Мне не нравится этот план"
   Выход: "На уровне вайба я чувствую нерелевантность текущего трека —
   предлагаю выровнять ожидания и пересобрать подход."

3. Вход: "Сотрудники жалуются на переработки"
   Выход: "Есть запрос от команды на оптимизацию workload — нужно
   синкнуться и зафиксировать отдельным треком."

4. Вход: "Мы потратили много денег на ерунду"
   Выход: "Освоили значительный объём ликвидности на инициативы
   с сомнительной релевантностью — валидный вызов для пересборки."

ГРАНИЦЫ (жёстко):
- НЕ используй мат и прямые оскорбления. Стиль — пародия на пафос,
  а не хамство.
- НЕ добавляй конкретику, которой не было во входе (цифры, имена, сроки).
- НЕ превращай текст в полную бессмыслицу: исходный смысл должен
  угадываться.
- НЕ используй больше 2–3 англицизмов на предложение.
- Если входная фраза уже звучит как корпоративный жаргон —
  верни её же с пометкой "(уже на языке)".

ФОРМАТ: только переписанный текст, без комментариев и кавычек.
"""

SYSTEM_PROMPT_ESO = """
Ты — переводчик на эзотерико-осознанный язык. Это сленг практиков
духовного развития и психологии осознанности: слова как вибрации,
замена «негативных» конструкций, отказ от позиции жертвы, метафоры.

ПРИМЕРЫ ПЕРЕВОДА:
1. Вход: "Я устал и не хочу ничего делать"
   Выход: "Я чувствую слив энергии и выбираю сейчас состояние
   восстановления ресурса."

2. Вход: "Меня обидели"
   Выход: "Я выбрал прожить опыт обиды — это точка роста для меня."

3. Вход: "Мне придётся это сделать"
   Выход: "Я принял решение войти в этот процесс — это моё
   осознанное намерение."

4. Вход: "Всё плохо, ничего не получается"
   Выход: "Я в точке трансформации: то, что не резонирует,
   уходит, освобождая место для потока."

ГРАНИЦЫ (жёстко):
- НЕ используй мат и агрессию — стиль про «экологичность».
- НЕ добавляй диагнозы, медицинские советы, упоминания болезней.
- НЕ превращай текст в полную бессмыслицу: исходный смысл
  должен угадываться.
- НЕ используй больше 3 «сакральных» терминов на предложение
  (поток, ресурс, вибрации, принятие, трансформация, поле).
- НЕ убирай частицу «не» механически — переформулируй
  утвердительно, если это возможно.
- Если входная фраза уже эзотерическая — верни её же
  с пометкой "(уже на языке)".

ФОРМАТ: только переписанный текст, без комментариев и кавычек.
"""

# ============================================================
# GIGACHAT
# ============================================================

def translate_with_gigachat(text: str, system_prompt: str, model: str = "GigaChat-2") -> str:
    """Отправляет запрос в GigaChat с заданным системным промптом."""
    with GigaChat(model=model, verify_ssl_certs=False) as giga:
        response = giga.chat(
            Chat(
                messages=[
                    Messages(role=MessagesRole.SYSTEM, content=system_prompt),
                    Messages(role=MessagesRole.USER, content=text),
                ]
            )
        )
        return response.choices[0].message.content.strip()


# ============================================================
# FALLBACK (rule-based из lexicons.py)
# ============================================================

def apply_rules(text: str, rules) -> str:
    for pattern, repl, case_sensitive in rules:
        flags = 0 if case_sensitive else re.IGNORECASE
        text = re.sub(pattern, repl, text, flags=flags)
    return text


def corp_fallback(text: str) -> str:
    return CORP_PREFIX + apply_rules(text, CORP_RULES) + CORP_SUFFIX


def eso_fallback(text: str) -> str:
    body = apply_rules(text, ESO_RULES)
    body = re.sub(r"\s{2,}", " ", body).strip()
    return ESO_PREFIX + body + ESO_SUFFIX


# ============================================================
# ОСНОВНАЯ ФУНКЦИЯ
# ============================================================

def translate(text: str, use_llm: bool = True) -> dict:
    """Переводит фразу на оба регистра. При ошибке LLM — fallback."""
    if use_llm:
        try:
            return {
                "corporate": translate_with_gigachat(text, SYSTEM_PROMPT_CORP),
                "esoteric": translate_with_gigachat(text, SYSTEM_PROMPT_ESO),
            }
        except Exception as e:
            print(f"[WARN] GigaChat недоступен, использую fallback: {e}", file=sys.stderr)

    return {
        "corporate": corp_fallback(text),
        "esoteric": eso_fallback(text),
    }


if __name__ == "__main__":
    if len(sys.argv) > 1:
        phrase = " ".join(sys.argv[1:])
    else:
        phrase = input("Фраза: ")

    phrase = phrase.strip()

    if not phrase:
        print("Пустой ввод — нечего переводить.", file=sys.stderr)
        sys.exit(1)

    if len(phrase) > MAX_INPUT_CHARS:
        print(
            f"Слишком длинный ввод: {len(phrase)} символов. "
            f"Максимум — {MAX_INPUT_CHARS} (~3 предложения средней длины). "
            f"Сократите фразу и попробуйте снова.",
            file=sys.stderr,
        )
        sys.exit(1)

    result = translate(phrase)
    print("\n=== Корпоративно-ебланский ===")
    print(result["corporate"])
    print("\n=== Эзотерико-осознанный ===")
    print(result["esoteric"])
  
